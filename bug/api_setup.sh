    [[ -n "$(kget FULLHUNT_API_KEY)" ]]       && echo "fullhunt:"       && echo "  - $(kget FULLHUNT_API_KEY)"
    [[ -n "$(kget INTELX_API_KEY)" ]]         && echo "intelx:"         && echo "  - $(kget INTELX_API_KEY)"
    [[ -n "$(kget WHOISXML_API_KEY)" ]]       && echo "whoisxmlapi:"    && echo "  - $(kget WHOISXML_API_KEY)"
    [[ -n "$(kget FOFA_API_KEY)" ]]           && echo "fofa:"           && echo "  - $(kget FOFA_EMAIL):$(kget FOFA_API_KEY)"
    [[ -n "$(kget CERTSPOTTER_API_KEY)" ]]    && echo "certspotter:"    && echo "  - $(kget CERTSPOTTER_API_KEY)"
    [[ -n "$(kget DNSDB_API_KEY)" ]]          && echo "dnsdb:"          && echo "  - $(kget DNSDB_API_KEY)"
    [[ -n "$(kget BUILTWITH_API_KEY)" ]]      && echo "builtwith:"      && echo "  - $(kget BUILTWITH_API_KEY)"
    [[ -n "$(kget ZOOMEYE_API_KEY)" ]]        && echo "zoomeyeapi:"     && echo "  - $(kget ZOOMEYE_API_KEY)"
    [[ -n "$(kget QUAKE_API_KEY)" ]]          && echo "quake:"          && echo "  - $(kget QUAKE_API_KEY)"
    [[ -n "$(kget THREATBOOK_API_KEY)" ]]     && echo "threatbook:"     && echo "  - $(kget THREATBOOK_API_KEY)"
    [[ -n "$(kget C99_API_KEY)" ]]            && echo "c99:"            && echo "  - $(kget C99_API_KEY)"
    [[ -n "$(kget BEVIGIL_API_KEY)" ]]        && echo "bevigil:"        && echo "  - $(kget BEVIGIL_API_KEY)"
    [[ -n "$(kget PASSIVETOTAL_API_KEY)" ]]   && echo "passivetotal:"   && echo "  - $(kget PASSIVETOTAL_USERNAME):$(kget PASSIVETOTAL_API_KEY)"
    [[ -n "$(kget FACEBOOK_API_TOKEN)" ]]     && echo "facebook:"       && echo "  - $(kget FACEBOOK_API_TOKEN)"
    [[ -n "$(kget BUFFEROVER_API_KEY)" ]]     && echo "bufferover:"     && echo "  - $(kget BUFFEROVER_API_KEY)"
    [[ -n "$(kget CHINAZ_API_KEY)" ]]         && echo "chinaz:"         && echo "  - $(kget CHINAZ_API_KEY)"
    [[ -n "$(kget ROBTEX_API_KEY)" ]]         && echo "robtex:"         && echo "  - $(kget ROBTEX_API_KEY)"
    [[ -n "$(kget DNSREPO_API_KEY)" ]]        && echo "dnsrepo:"        && echo "  - $(kget DNSREPO_API_KEY)"
} > "$SUB_CFG"
chmod 600 "$SUB_CFG"
mark "subfinder → $SUB_CFG"

