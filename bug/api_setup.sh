#!/usr/bin/env bash
# api_setup.sh — Distributes api_keys.txt values to every tool's native config
# Sourced by install_tools.sh. Do not run standalone.

API_KEYS_FILE="${1:-./api_keys.txt}"

if [[ ! -f "$API_KEYS_FILE" ]]; then
    log_warn "api_keys.txt not found — skipping API configuration"
    log_info "Create it from the template, then re-run installer"
    return 0
fi

echo ""
echo -e "${MAGENTA}━━━ [7/8] API key distribution ━━━${NC}"

# ---------- Parse api_keys.txt (strip comments, blanks) ----------
declare -A KEY
while IFS='=' read -r k v; do
    k=$(echo "$k" | tr -d '[:space:]')
    v=$(echo "$v" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    [[ -z "$k" ]] && continue
    [[ "$k" =~ ^# ]] && continue
    [[ -z "$v" ]] && continue
    KEY["$k"]="$v"
done < "$API_KEYS_FILE"

KEY_COUNT=${#KEY[@]}
if [[ $KEY_COUNT -eq 0 ]]; then
    log_info "No API keys filled in — all tools will run in free mode"
    return 0
fi

log_info "Loaded $KEY_COUNT API key(s)"

# Helper: get key or empty
kget() { echo "${KEY[$1]:-}"; }

# Helper: mark configured
mark() { log_ok "$1 configured"; }

# ============================================================
# 1. SUBFINDER → ~/.config/subfinder/provider-config.yaml
# ============================================================
SUB_CFG="/root/.config/subfinder/provider-config.yaml"
mkdir -p "$(dirname "$SUB_CFG")"

