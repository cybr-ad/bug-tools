# ============================================================
# 4. SHODAN CLI → ~/.shodan/api_key  +  shodan init
# ============================================================
if [[ -n "$(kget SHODAN_API_KEY)" ]]; then
    mkdir -p /root/.shodan
    echo "$(kget SHODAN_API_KEY)" > /root/.shodan/api_key
    chmod 600 /root/.shodan/api_key
    if command -v shodan &>/dev/null; then
        shodan init "$(kget SHODAN_API_KEY)" >/dev/null 2>&1 && mark "shodan CLI initialized" || log_warn "shodan CLI init failed"
    fi
fi

# ============================================================
# 5. CHAOS → env var in .bashrc
# ============================================================
if [[ -n "$(kget CHAOS_API_KEY)" ]]; then
    for rc in /root/.bashrc /root/.profile; do
        grep -q 'CHAOS_KEY=' "$rc" 2>/dev/null || echo "export CHAOS_KEY=$(kget CHAOS_API_KEY)" >> "$rc"
    done
    echo "export CHAOS_KEY=$(kget CHAOS_API_KEY)" > /etc/profile.d/chaos.sh
    chmod +x /etc/profile.d/chaos.sh
    mark "chaos → env CHAOS_KEY"
fi

# ============================================================
# 6. PDCP (nuclei) → env var + ~/.pdcp/
# ============================================================
PDCP_VAL="$(kget PDCP_API_KEY)"
[[ -z "$PDCP_VAL" ]] && PDCP_VAL="$(kget CHAOS_API_KEY)"   # reuse Chaos if blank
if [[ -n "$PDCP_VAL" ]]; then
    for rc in /root/.bashrc /root/.profile; do
        grep -q 'PDCP_API_KEY=' "$rc" 2>/dev/null || echo "export PDCP_API_KEY=$PDCP_VAL" >> "$rc"
    done
    echo "export PDCP_API_KEY=$PDCP_VAL" > /etc/profile.d/pdcp.sh
    chmod +x /etc/profile.d/pdcp.sh
    mkdir -p /root/.pdcp
    echo "api-key: $PDCP_VAL" > /root/.pdcp/credentials.yaml
    chmod 600 /root/.pdcp/credentials.yaml
    mark "nuclei/PDCP → env PDCP_API_KEY + ~/.pdcp/"
fi

# ============================================================
# 7. GITHUB TOKEN → env for github-search / github-subdomains
# ============================================================
if [[ -n "$(kget GITHUB_TOKEN)" ]]; then
    for rc in /root/.bashrc /root/.profile; do
        grep -q 'GITHUB_TOKEN=' "$rc" 2>/dev/null || echo "export GITHUB_TOKEN=$(kget GITHUB_TOKEN)" >> "$rc"
    done
    echo "export GITHUB_TOKEN=$(kget GITHUB_TOKEN)" > /etc/profile.d/github.sh
    chmod +x /etc/profile.d/github.sh
    mark "github-search → env GITHUB_TOKEN"
fi

# ============================================================
# 8. METABIGOR → ~/.config/metabigor/ (Shodan, Censys)
# ============================================================
MG_CFG="/root/.config/metabigor/config.yaml"
if [[ -n "$(kget SHODAN_API_KEY)" ]] || [[ -n "$(kget CENSYS_API_ID)" ]]; then
    mkdir -p "$(dirname "$MG_CFG")"
    {
        [[ -n "$(kget SHODAN_API_KEY)" ]] && echo "shodan:" && echo "  - $(kget SHODAN_API_KEY)"
        [[ -n "$(kget CENSYS_API_ID)" ]]  && echo "censys:" && echo "  - $(kget CENSYS_API_ID):$(kget CENSYS_API_SECRET)"
    } > "$MG_CFG"
    chmod 600 "$MG_CFG"
    mark "metabigor → $MG_CFG"
fi

# ============================================================
# 9. VERIFICATION — test live queries
# ============================================================
echo ""
echo -e "${CYAN}  Verifying API keys with live queries...${NC}"

if command -v subfinder &>/dev/null && [[ -n "$(kget SHODAN_API_KEY)$(kget VIRUSTOTAL_API_KEY)$(kget CHAOS_API_KEY)" ]]; then
    RES=$(subfinder -d example.com -silent -timeout 10 2>/dev/null | head -1)
    [[ -n "$RES" ]] && log_ok "subfinder responds ($RES …)" || log_warn "subfinder returned nothing (keys may be invalid)"
fi

if command -v chaos &>/dev/null && [[ -n "$(kget CHAOS_API_KEY)" ]]; then
    RES=$(chaos -d example.com -silent 2>/dev/null | head -1)
    [[ -n "$RES" ]] && log_ok "chaos API key works" || log_warn "chaos API key invalid or no results"
fi

if command -v shodan &>/dev/null && [[ -n "$(kget SHODAN_API_KEY)" ]]; then
    if shodan info 2>/dev/null | grep -q "Query credits"; then
        log_ok "shodan API key works"
    else
        log_warn "shodan API key invalid"
    fi
fi

if command -v theHarvester &>/dev/null && [[ -n "$(kget HUNTER_API_KEY)" ]]; then
    log_ok "theHarvester config written (test manually: theHarvester -d example.com -b hunter)"
fi

echo ""
log_info "API key distribution complete"
