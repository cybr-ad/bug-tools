    echo "apikey = $(kget INTELX_API_KEY)"
    echo ""

    echo "[data_sources.WhoisXML]"
    echo "[data_sources.WhoisXML.Credentials]"
    echo "apikey = $(kget WHOISXML_API_KEY)"
    echo ""

    echo "[data_sources.Fofa]"
    echo "[data_sources.Fofa.Credentials]"
    echo "email = $(kget FOFA_EMAIL)"
    echo "apikey = $(kget FOFA_API_KEY)"
    echo ""

    echo "[data_sources.CertSpotter]"
    echo "[data_sources.CertSpotter.Credentials]"
