# 3. THEHARVESTER → ~/.theHarvester/api-keys.yaml
# ============================================================
TH_CFG="/root/.theHarvester/api-keys.yaml"
mkdir -p "$(dirname "$TH_CFG")"

{
    echo "apikeys:"
    [[ -n "$(kget SHODAN_API_KEY)" ]]      && echo "  shodan:"       && echo "    key: $(kget SHODAN_API_KEY)"
    [[ -n "$(kget CENSYS_API_ID)" ]]       && echo "  censys:"       && echo "    token: $(kget CENSYS_API_ID)" && echo "    organization_id: $(kget CENSYS_API_SECRET)"
    [[ -n "$(kget VIRUSTOTAL_API_KEY)" ]]  && echo "  virustotal:"   && echo "    key: $(kget VIRUSTOTAL_API_KEY)"
    [[ -n "$(kget SECURITYTRAILS_API_KEY)" ]] && echo "  securitytrails:" && echo "    key: $(kget SECURITYTRAILS_API_KEY)"
    [[ -n "$(kget BINARYEDGE_API_KEY)" ]]  && echo "  binaryedge:"   && echo "    key: $(kget BINARYEDGE_API_KEY)"
    [[ -n "$(kget GITHUB_TOKEN)" ]]        && echo "  github:"       && echo "    key: $(kget GITHUB_TOKEN)"
    [[ -n "$(kget HUNTER_API_KEY)" ]]      && echo "  hunter:"       && echo "    key: $(kget HUNTER_API_KEY)"
    [[ -n "$(kget INTELX_API_KEY)" ]]      && echo "  intelx:"       && echo "    key: $(kget INTELX_API_KEY)"
    [[ -n "$(kget WHOISXML_API_KEY)" ]]    && echo "  whoisxmlapi:"  && echo "    key: $(kget WHOISXML_API_KEY)"
    [[ -n "$(kget FULLHUNT_API_KEY)" ]]    && echo "  fullhunt:"     && echo "    key: $(kget FULLHUNT_API_KEY)"
    [[ -n "$(kget HIBP_API_KEY)" ]]        && echo "  hibpverified:" && echo "    key: $(kget HIBP_API_KEY)"
    [[ -n "$(kget TOMBA_API_KEY)" ]]       && echo "  tomba:"        && echo "    key: $(kget TOMBA_API_KEY)" && echo "    secret: $(kget TOMBA_API_SECRET)"
    [[ -n "$(kget CERTSPOTTER_API_KEY)" ]] && echo "  certspotter:"  && echo "    key: $(kget CERTSPOTTER_API_KEY)"
    [[ -n "$(kget BUILTWITH_API_KEY)" ]]   && echo "  builtwith:"    && echo "    key: $(kget BUILTWITH_API_KEY)"
    [[ -n "$(kget ROUTEVIEWS_API_KEY)" ]]  && echo "  routeviews:"   && echo "    key: $(kget ROUTEVIEWS_API_KEY)"
    [[ -n "$(kget BEVIGIL_API_KEY)" ]]     && echo "  bevigil:"      && echo "    key: $(kget BEVIGIL_API_KEY)"
